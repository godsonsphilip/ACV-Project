                    "import torch.nn as nn\n",
                    "import torch.nn.functional as F\n",
                    "from torchinfo import summary\n",
                    "\n",
                    "class ConvBlock(nn.Module):\n",
                    "    def __init__(self, in_ch, out_ch):\n",
                    "        super().__init__()\n",
                    "        self.block = nn.Sequential(\n",
                    "            nn.Conv2d(in_ch, out_ch, kernel_size=3, padding=1, bias=False),\n",
                    "            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True),\n",
                    "            nn.Conv2d(out_ch, out_ch, kernel_size=3, padding=1, bias=False),\n",
                    "            nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True)\n",
                    "        )\n",
                    "    def forward(self, x):\n",
                    "        return self.block(x)\n",
                    "\n",
                    "class DecoderStage(nn.Module):\n",
                    "    def __init__(self, in_ch, out_ch, use_skip=False, skip_ch=0):\n",
                    "        super().__init__()\n",
                    "        self.use_skip = use_skip\n",
                    "        self.up_conv = nn.Sequential(nn.Conv2d(in_ch, out_ch, kernel_size=1, bias=False), nn.BatchNorm2d(out_ch), nn.ReLU(inplace=True))\n",
                    "        self.conv = ConvBlock((out_ch + skip_ch) if use_skip else out_ch, out_ch)\n",
                    "    def forward(self, x, skip=None):\n",
                    "        x = F.interpolate(x, scale_factor=2.0, mode='bilinear', align_corners=False)\n",
                    "        x = self.up_conv(x)\n",
                    "        if self.use_skip and skip is not None:\n",
                    "            if x.shape[2:] != skip.shape[2:]:\n",
                    "                x = F.interpolate(x, size=skip.shape[2:], mode='bilinear', align_corners=False)\n",
                    "            x = torch.cat([x, skip], dim=1)\n",
                    "        return self.conv(x)\n",
                    "\n",
                    "class Segmenter(nn.Module):\n",
                    "    def __init__(self, use_skips=False, num_classes=12):\n",
                    "        super().__init__()\n",
                    "        self.use_skips = use_skips\n",
                    "        self.enc1 = ConvBlock(3, 32);   self.pool1 = nn.MaxPool2d(2)\n",
                    "        self.enc2 = ConvBlock(32, 64);  self.pool2 = nn.MaxPool2d(2)\n",
                    "        self.enc3 = ConvBlock(64, 128); self.pool3 = nn.MaxPool2d(2)\n",
                    "        self.enc4 = ConvBlock(128, 256);self.pool4 = nn.MaxPool2d(2)\n",
                    "        self.bottleneck = ConvBlock(256, 512)\n",
                    "        self.dec4 = DecoderStage(512, 256, use_skips, 256 if use_skips else 0)\n",
                    "        self.dec3 = DecoderStage(256, 128, use_skips, 128 if use_skips else 0)\n",
                    "        self.dec2 = DecoderStage(128, 64, use_skips, 64 if use_skips else 0)\n",
                    "        self.dec1 = DecoderStage(64, 32, use_skips, 32 if use_skips else 0)\n",
                    "        self.head = nn.Conv2d(32, num_classes, kernel_size=1)\n",
                    "\n",
                    "    def forward(self, x):\n",
                    "        e1 = self.enc1(x); p1 = self.pool1(e1)\n",
                    "        e2 = self.enc2(p1); p2 = self.pool2(e2)\n",
                    "        e3 = self.enc3(p2); p3 = self.pool3(e3)\n",
                    "        e4 = self.enc4(p3); p4 = self.pool4(e4)\n",
                    "        b = self.bottleneck(p4)\n",
                    "        d4 = self.dec4(b, e4 if self.use_skips else None)\n",
                    "        d3 = self.dec3(d4, e3 if self.use_skips else None)\n",
                    "        d2 = self.dec2(d3, e2 if self.use_skips else None)\n",
                    "        d1 = self.dec1(d2, e1 if self.use_skips else None)\n",
                    "        return self.head(d1)\n",
                    "\n",
                    "model_a = Segmenter(use_skips=False)\n",
                    "model_b = Segmenter(use_skips=True)\n",
